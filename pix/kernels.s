@ ---- Row kernels: "T3" rows, three groups of four inputs per word of steps ----
@ void tern_scan(int32_t *out, const uint8_t *steps, const int32_t *tbl, int ngroups, int nrows)
@ out[r] = the sum, over the row's groups, of the table entry each group selects (see tern_build81).
@ A word of steps is A << 24 | B << 11 | C (export.py step_words). With p at the entry of the group before the word:
@   [p, w lsr #9]     the first group's entry, B words on. The bits of A arrive 32 KB and more above the address: fast
@                     RAM repeats every 32 KB up to 0x03FFFFFF, so the read lands on the same entry (A < 256: at most
@                     8 MB above). No masking, no write-back.
@   [p, w lsr #22]!   the second group's entry, A words on from the same p (bits 22 and 23 of w are zero).
@   and + [p, C]!     the third group's, C words on from the second.
@ 13 cycles for three groups and 4 for the word from ROM, against 15 + 3 with one step byte per group.
@ When the number of groups is not a multiple of three, the row's FIRST word is the short one (two groups: B and A;
@ one group: A). Rows of 48, 32, 24 and 16 groups are fully unrolled; other lengths go to scan_c (pix.c) in ROM.
@ The tables must be in fast RAM (they always are: tbl in pix.c).
    .macro T3 w
    ldr     r11, [r6, \w, lsr #9]
    add     r7, r7, r11
    ldr     r11, [r6, \w, lsr #22]!
    add     r7, r7, r11
    and     r10, \w, #0xFF
    ldr     r11, [r6, r10, lsl #2]!
    add     r7, r7, r11
    .endm
    .macro T3F2 w                   @ a row's first word when it holds two groups: starts the sum (r2 = tables - 4)
    ldr     r7, [r2, \w, lsr #9]
    add     r6, r2, \w, lsr #22
    ldr     r11, [r6]
    add     r7, r7, r11
    .endm
    .macro T3F w                    @ a row's first word, three groups
    T3F2    \w
    and     r10, \w, #0xFF
    ldr     r11, [r6, r10, lsl #2]!
    add     r7, r7, r11
    .endm
    .global tern_scan
    .type   tern_scan, %function
tern_scan:
    cmp     r3, #48
    cmpne   r3, #32
    cmpne   r3, #24
    cmpne   r3, #16
    ldrne   r12, 1f                 @ any other length: the C loop in ROM (no model uses one);
    bxne    r12                     @ bx, because scan_c is Thumb code
    push    {r4-r11, lr}
    ldr     r5, [sp, #36]
    sub     r2, r2, #4
    cmp     r3, #32
    beq     .Lscan32
    bhi     .Lscan48
    cmp     r3, #24
    beq     .Lscan24
    b       .Lscan16
1:  .word   scan_c
.Lscan48:
    ldmia   r1!, {r3, r4, r8, r9, r12, r14}
    T3F     r3
    T3      r4
    T3      r8
    T3      r9
    T3      r12
    T3      r14
    ldmia   r1!, {r3, r4, r8, r9, r12}
    T3      r3
    T3      r4
    T3      r8
    T3      r9
    T3      r12
    ldmia   r1!, {r3, r4, r8, r9, r12}
    T3      r3
    T3      r4
    T3      r8
    T3      r9
    T3      r12
    str     r7, [r0], #4
    subs    r5, r5, #1
    bne     .Lscan48
    b       .Lsret
.Lscan32:
    ldmia   r1!, {r3, r4, r8, r9, r12, r14}
    T3F2    r3
    T3      r4
    T3      r8
    T3      r9
    T3      r12
    T3      r14
    ldmia   r1!, {r3, r4, r8, r9, r12}
    T3      r3
    T3      r4
    T3      r8
    T3      r9
    T3      r12
    str     r7, [r0], #4
    subs    r5, r5, #1
    bne     .Lscan32
    b       .Lsret
.Lscan24:
    ldmia   r1!, {r3, r4, r8, r9}
    T3F     r3
    T3      r4
    T3      r8
    T3      r9
    ldmia   r1!, {r3, r4, r8, r9}
    T3      r3
    T3      r4
    T3      r8
    T3      r9
    str     r7, [r0], #4
    subs    r5, r5, #1
    bne     .Lscan24
    b       .Lsret
.Lscan16:
    ldmia   r1!, {r3, r4, r8, r9, r12, r14}
    add     r6, r2, r3, lsr #22     @ the first word holds one group
    ldr     r7, [r6]
    T3      r4
    T3      r8
    T3      r9
    T3      r12
    T3      r14
    str     r7, [r0], #4
    subs    r5, r5, #1
    bne     .Lscan16
.Lsret:
    pop     {r4-r11, lr}
    bx      lr

@ int tern_scan_relu(int32_t *vals, const uint8_t *steps, const int32_t *tbl, int nwords, ScanR *r)
@ int tern_scan_x(int32_t *vals, const uint8_t *steps, const int32_t *tbl, int nwords, ScanR *r)      nwords = D / 16
@ The MLP's first matrix with the squared ReLU applied to each row sum as it is ready (see pix.c): the sums are not
@ stored. r = { m, shift, 32 - shift, 2^(shift-1), in0, rows, idx - vals / 2, dif - vals, two, sum0, sum1 }.
@ tern_scan_relu: two streams, rows of 32 groups (the first-pass models with guidance). The tables' first group has
@ -in0 in both halves of every entry, so a half is kept when it is not negative. As relu_sq2, which see: v_hi to vals,
@ v_lo - v_hi to dif, the row number to idx, the sums to r. A dropped row costs 8 cycles beyond its steps.
@ tern_scan_x: one stream, rows of 48 or 32 groups, with early exit (pix.c, W1X). The tables carry the limits: the sum
@ so far is negative at a check point (28, 24, ... 4 groups to go) when the row is below that point's limit, and
@ negative at the end when the row is below in0. As relu_sq: v to vals, the row number to idx.
@ The last ten words of a row are the same code for both lengths (macro XTAIL), assembled once for each.
@ Assembled with --defsym NOW1X=1 the check points are left out (for builds with W1X 0; pix.c then gives limits
@ that never trigger, so both ways of assembling are right for it).
@ Both return the count. Their entry code is in ROM; pix_begin writes the model's shift into the nine instructions
@ listed in relu_sites. In the loops: r5 = row - rows.
@ On the stack: in0, m, rows, idx offset, dif offset, sum0, sum1, start of vals, r.
    .macro CKADD ck, n, out
    .if \ck == \n
    adds    r7, r7, r11
    .ifndef NOW1X
    bmi     \out
    .endif
    .else
    add     r7, r7, r11
    .endif
    .endm
    .macro T3X w, ck, out           @ T3 with a check point after its first (1), second (2) or third (3) group
    ldr     r11, [r6, \w, lsr #9]
    CKADD   \ck, 1, \out
    ldr     r11, [r6, \w, lsr #22]!
    CKADD   \ck, 2, \out
    and     r10, \w, #0xFF
    ldr     r11, [r6, r10, lsl #2]!
    CKADD   \ck, 3, \out
    .endm
    .macro XTAIL a, b, c, d, e, sfx @ a row's last ten words; \a..\e hold the first five, loaded with the words before
    T3X     \a, 2, .Lxa\sfx         @ 28 groups to go
    T3X     \b, 3, .Lxa\sfx         @ 24
    T3      \c
    T3X     \d, 1, .Lxa\sfx         @ 20
    T3X     \e, 2, .Lxa\sfx         @ 16
    ldmia   r1!, {r3, r4, r8, r9, r12}
    T3X     r3, 3, .Lxn\sfx         @ 12
    T3      r4
    T3X     r8, 1, .Lxn\sfx         @ 8
    T3X     r9, 2, .Lxn\sfx         @ 4
    ldr     r11, [r6, r12, lsr #9]
    add     r7, r7, r11
    ldr     r11, [r6, r12, lsr #22]!
    add     r7, r7, r11
    and     r10, r12, #0xFF
    ldr     r11, [r6, r10, lsl #2]!
    adds    r7, r7, r11
    blpl    .Lkeep1                 @ kept when the sum (- in0) is not negative
.Lxn\sfx:
    adds    r5, r5, #1
    bne     .Lx\sfx
    b       .Lrexit
    .ifndef NOW1X
.Lxa\sfx:
    add     r1, r1, #20             @ the row's last five words were not loaded yet
    adds    r5, r5, #1
    bne     .Lx\sfx
    b       .Lrexit
    .endif
    .endm
.Lx16:                              @ one stream, 48 groups
    ldmia   r1!, {r3, r4, r8, r9, r12, r14}
    T3F     r3
    T3      r4
    T3      r8
    T3      r9
    T3      r12
    T3      r14
    ldmia   r1!, {r3, r4, r8, r9, r12}
    XTAIL   r3, r4, r8, r9, r12, 16
.Lx11:                              @ one stream, 32 groups
    ldmia   r1!, {r3, r4, r8, r9, r12, r14}
    T3F2    r3
    XTAIL   r4, r8, r9, r12, r14, 11
.Lkeep1:                            @ a kept row (about one in four): r7 = row sum - in0; returns to lr
    ldmia   sp, {r3, r4, r6, r8}    @ in0, m, rows, idx offset
    add     r7, r7, r3              @ the row sum
    add     r6, r6, r5              @ row number
    add     r8, r8, r0, lsr #1
    strh    r6, [r8]
    smull   r10, r11, r4, r7
    adds    r10, r10, #0x8000
    adc     r11, r11, #0
    mov     r10, r10, lsr #16
    orr     r10, r10, r11, lsl #16  @ p
    umull   r4, r11, r10, r10
.Lfa0:
    adds    r4, r4, #0x8000         @ (the shift, 16 here, is written into these by pix_begin)
    adc     r11, r11, #0
.Lfl0:
    mov     r4, r4, lsr #16
.Lfo0:
    orr     r4, r4, r11, lsl #16    @ v
    str     r4, [r0], #4
    bx      lr
.Lrelu11:                           @ two streams, 32 groups, with stream 0's early exit (PIX_W1XS0: the packed sum's sign
    ldmia   r1!, {r3, r4, r8, r9, r12, r14}         @ is the high half's; the tables carry w1xb2's limits)
