@ One head's key scan, distance bias and top 8 in one pass; the scores are not stored. The nrows keys (nwords = 2 or 3
@ words of steps each) end at kend and are scanned from the last (row j0 + nrows - 1, the nearest cell) down to row
@ j0; bias is read forwards, two rows per load. A score that reaches the 8th best so far is inserted unless skip
@ (may be 0) marks its row. tv: 9 pairs (score, row): pair 0 is a stop for the insertion walk (the largest score
@ there is), pairs 1..8 the best, best first, among equals the lower row first; tv[18] = how many, also returned.
@ Two-word keys (sign-only, 16 values per word: the 16x16 models): rest = the most a row's second word of steps can
@ add, worked out here from the table. A row whose first word plus bias plus rest stays below the 8th best so far
